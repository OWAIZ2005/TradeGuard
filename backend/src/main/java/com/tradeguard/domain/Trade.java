package com.tradeguard.domain;

import jakarta.persistence.*;
import java.math.BigDecimal;
import java.time.Instant;

/** One uploaded CSV row, valid or not. Analytics read only {@link ValidationStatus#VALID} rows. */
@Entity
@Table(name = "trades")
public class Trade {

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "trades_seq")
    @SequenceGenerator(name = "trades_seq", sequenceName = "trades_seq", allocationSize = 50)
    private Long id;

    @Column(name = "batch_id", nullable = false)
    private Long batchId;

    @Column(name = "row_number", nullable = false)
    private int rowNumber;

    @Column(name = "trade_id")
    private String tradeId;

    private String instrument;

    @Column(name = "trade_timestamp")
    private Instant tradeTimestamp;

    private String side;
    private BigDecimal price;
    private BigDecimal quantity;
    private String currency;

    @Column(name = "trader_id")
    private String traderId;

    @Column(name = "raw_record", nullable = false)
    private String rawRecord;

    @Enumerated(EnumType.STRING)
    @Column(name = "validation_status", nullable = false)
    private ValidationStatus validationStatus;

    @Column(name = "effective_at", nullable = false)
    private Instant effectiveAt;

    /** Generated by PostgreSQL as price * quantity; read-only for Hibernate. */
    @Column(insertable = false, updatable = false)
    private BigDecimal notional;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Trade() {
    }

    public Trade(Long batchId, int rowNumber, String tradeId, String instrument, Instant tradeTimestamp, String side,
                 BigDecimal price, BigDecimal quantity, String currency, String traderId, String rawRecord,
                 ValidationStatus validationStatus, Instant effectiveAt) {
        this.batchId = batchId;
        this.rowNumber = rowNumber;
        this.tradeId = tradeId;
        this.instrument = instrument;
        this.tradeTimestamp = tradeTimestamp;
        this.side = side;
        this.price = price;
        this.quantity = quantity;
        this.currency = currency;
        this.traderId = traderId;
        this.rawRecord = rawRecord;
        this.validationStatus = validationStatus;
        this.effectiveAt = effectiveAt;
    }

    @PrePersist
    void onCreate() {
        createdAt = Instant.now();
        updatedAt = createdAt;
    }

    @PreUpdate
    void onUpdate() {
        updatedAt = Instant.now();
    }

    public Long getId() { return id; }
    public Long getBatchId() { return batchId; }
    public int getRowNumber() { return rowNumber; }
    public String getTradeId() { return tradeId; }
    public ValidationStatus getValidationStatus() { return validationStatus; }
}
