package com.tradeguard;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.containsString;
import static org.hamcrest.Matchers.hasItem;
import static org.hamcrest.Matchers.hasSize;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.util.List;
import org.junit.jupiter.api.Test;

class ImportIntegrationTest extends AbstractIntegrationTest {

    private static final String MIXED = String.join("\n",
            "A-1,ES,2025-03-10T14:30:00Z,BUY,5100.25,10,USD,TRD-1",            // row 2 valid
            "A-2,NQ,2025-03-10T15:00:00Z,SELL,18000.50,5,USD,TRD-2",           // row 3 valid
            ",ES,2025-03-10T15:00:00Z,BUY,5100,1,USD,TRD-1",                   // row 4 missing id
            "A-4,ES,2025-03-10T15:00:00Z,BUY,-5,1,USD,TRD-1",                  // row 5 negative price
            "A-5,ES,not-a-date,BUY,5100,1,USD,TRD-1",                          // row 6 bad timestamp
            "A-1,ES,2025-03-11T10:00:00Z,SELL,5101,2,USD,TRD-3",               // row 7 duplicate of row 2
            "A-7,ES,2025-03-11T10:00:00Z,HOLD,5101,0,USD,TRD-3",               // row 8 bad side + zero qty
            "A-8,GC,2025-03-11T11:00:00Z,SELL,2300.10,3,EUR,TRD-4",            // row 9 valid (EUR)
            "");

    @Test
    void importsAValidFileEndToEnd() throws Exception {
        uploadCsv("T-1,ES,2025-03-10T14:30:00Z,BUY,5100.25,10,USD,TRD-1\n"
                + "T-2,NQ,2025-03-11T15:00:00+02:00,SELL,18000.50,5,usd,TRD-2\n")
                .andExpect(status().isCreated())
                .andExpect(header().string("Location", containsString("/api/imports/")))
                .andExpect(jsonPath("$.batch.status").value("COMPLETED"))
                .andExpect(jsonPath("$.batch.totalRows").value(2))
                .andExpect(jsonPath("$.batch.validRows").value(2))
                .andExpect(jsonPath("$.batch.invalidRows").value(0))
                .andExpect(jsonPath("$.batch.errorRatePercent").value(0.0))
                .andExpect(jsonPath("$.summary.headline").value("All 2 rows passed validation."))
                .andExpect(jsonPath("$.errorBreakdown", hasSize(0)));

        assertThat(countRows("trades")).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM trades WHERE validation_status='VALID'", Long.class))
                .isEqualTo(2);
        // normalised: lower-case currency stored upper-case; offset converted to UTC; notional generated by the DB
        assertThat(jdbc.queryForObject("SELECT currency FROM trades WHERE trade_id='T-2'", String.class))
                .isEqualTo("USD");
        assertThat(jdbc.queryForObject("SELECT to_char(trade_timestamp AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI')"
                + " FROM trades WHERE trade_id='T-2'", String.class)).isEqualTo("2025-03-11T13:00");
        assertThat(jdbc.queryForObject("SELECT notional FROM trades WHERE trade_id='T-1'", java.math.BigDecimal.class))
                .isEqualByComparingTo("51002.50");
    }

    @Test
    void mixedFileSeparatesValidFromInvalidAndKeepsRowNumbers() throws Exception {
        uploadCsv(MIXED)
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.batch.totalRows").value(8))
                .andExpect(jsonPath("$.batch.validRows").value(3))
                .andExpect(jsonPath("$.batch.invalidRows").value(5))
                .andExpect(jsonPath("$.batch.duplicateRows").value(1))
                .andExpect(jsonPath("$.batch.errorCount").value(6))
                .andExpect(jsonPath("$.summary.headline").value(containsString("5 of 8 rows")));

        long batchId = jdbc.queryForObject("SELECT id FROM trade_import_batches", Long.class);
        mvc.perform(get("/api/imports/{id}/errors", batchId).param("size", "50"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.totalElements").value(6))
                .andExpect(jsonPath("$.content[?(@.rowNumber==4)].code").value(hasItem("MISSING_TRADE_ID")))
                .andExpect(jsonPath("$.content[?(@.rowNumber==5)].code").value(hasItem("NON_POSITIVE_PRICE")))
                .andExpect(jsonPath("$.content[?(@.rowNumber==6)].code").value(hasItem("INVALID_TIMESTAMP")))
                .andExpect(jsonPath("$.content[?(@.rowNumber==6)].rejectedValue").value(hasItem("not-a-date")))
                .andExpect(jsonPath("$.content[?(@.rowNumber==7)].code").value(hasItem("DUPLICATE_IN_BATCH")))
                .andExpect(jsonPath("$.content[?(@.rowNumber==8)].code").value(hasItem("UNSUPPORTED_SIDE")))
                .andExpect(jsonPath("$.content[?(@.rowNumber==8)].code").value(hasItem("NON_POSITIVE_QUANTITY")));

        mvc.perform(get("/api/imports/{id}/errors", batchId).param("code", "duplicate_in_batch"))
                .andExpect(jsonPath("$.totalElements").value(1))
                .andExpect(jsonPath("$.content[0].message").value(containsString("row 2")));
    }

    @Test
    void persistsBatchTradesAndErrorsConsistently() throws Exception {
        uploadCsv(MIXED).andExpect(status().isCreated());

        assertThat(countRows("trade_import_batches")).isEqualTo(1);
        assertThat(countRows("trades")).isEqualTo(8); // every row is kept for audit
        assertThat(countRows("trade_validation_errors")).isEqualTo(6);
        assertThat(jdbc.queryForObject(
                "SELECT count(*) FROM trades WHERE validation_status='VALID'", Long.class)).isEqualTo(3);
        assertThat(jdbc.queryForObject("SELECT status FROM trade_import_batches", String.class))
                .isEqualTo("COMPLETED");
        assertThat(jdbc.queryForObject("SELECT rules_snapshot FROM trade_import_batches", String.class))
                .contains("allowedCurrencies").contains("maxTradeQuantity");
        assertThat(jdbc.queryForObject("SELECT length(file_sha256) FROM trade_import_batches", Integer.class))
                .isEqualTo(64);
        // every error points to a stored INVALID row
        assertThat(jdbc.queryForObject("""
                SELECT count(*) FROM trade_validation_errors e JOIN trades t ON t.id = e.trade_pk
                WHERE t.validation_status = 'INVALID'""", Long.class)).isEqualTo(6);
        // raw source row is kept for inspection
        assertThat(jdbc.queryForObject("SELECT raw_record FROM trades WHERE row_number = 6", String.class))
                .contains("not-a-date");
    }

    @Test
    void secondImportOfTheSameFileIsRejectedAsDuplicatesAndNeverOverwrites() throws Exception {
        String csv = "D-1,ES,2025-03-10T14:30:00Z,BUY,5100.25,10,USD,TRD-1\n"
                + "D-2,NQ,2025-03-10T14:31:00Z,SELL,18000.50,5,USD,TRD-2\n";
        uploadCsv(csv).andExpect(status().isCreated()).andExpect(jsonPath("$.batch.validRows").value(2));

        uploadCsv(csv)
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.batch.validRows").value(0))
                .andExpect(jsonPath("$.batch.invalidRows").value(2))
                .andExpect(jsonPath("$.batch.duplicateRows").value(2))
                .andExpect(jsonPath("$.errorBreakdown[0].code").value("DUPLICATE_EXISTING"))
                .andExpect(jsonPath("$.summary.points[0]").value(containsString("already imported")));

        assertThat(jdbc.queryForObject(
                "SELECT count(*) FROM trades WHERE validation_status='VALID'", Long.class)).isEqualTo(2);
        // original valid row still belongs to batch 1, untouched
        assertThat(jdbc.queryForObject(
                "SELECT batch_id FROM trades WHERE trade_id='D-1' AND validation_status='VALID'", Long.class))
                .isEqualTo(1L);
        assertThat(jdbc.queryForObject(
                "SELECT message FROM trade_validation_errors WHERE batch_id = 2 AND row_number = 2", String.class))
                .contains("batch 1, row 2");
    }

    @Test
    void invalidRowsDoNotClaimTheirTradeIdSoACorrectedRowIsAccepted() throws Exception {
        uploadCsv("C-1,ES,2025-03-10T14:30:00Z,BUY,-1,10,USD,TRD-1\n"
                + "C-1,ES,2025-03-10T14:31:00Z,BUY,5100,10,USD,TRD-1\n")
                .andExpect(jsonPath("$.batch.validRows").value(1))
                .andExpect(jsonPath("$.batch.duplicateRows").value(0));
    }

    @Test
    void rejectsNonCsvFileTypes() throws Exception {
        upload("trades.txt", "text/plain", HEADER + "\nT-1,ES,2025-03-10T14:30:00Z,BUY,1,1,USD,A\n")
                .andExpect(status().isUnsupportedMediaType())
                .andExpect(jsonPath("$.code").value("UNSUPPORTED_FILE_TYPE"))
                .andExpect(jsonPath("$.status").value(415));
        upload("trades.csv", "image/png", HEADER + "\n")
                .andExpect(status().isUnsupportedMediaType());
        upload("trades.csv", "text/csv", new byte[]{'P', 'K', 3, 4, 0, 0, 0, 1, 2})
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("NOT_A_TEXT_FILE"));
        assertThat(countRows("trade_import_batches")).isZero();
    }

    @Test
    void rejectsEmptyFilesAndHeaderOnlyFiles() throws Exception {
        upload("empty.csv", "text/csv", new byte[0])
                .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value("EMPTY_FILE"));
        upload("header-only.csv", "text/csv", HEADER + "\n")
                .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value("EMPTY_FILE"));
        assertThat(countRows("trade_import_batches")).isZero();
    }

    @Test
    void rejectsMissingRequiredHeadersAndNamesThem() throws Exception {
        upload("bad.csv", "text/csv", "trade_id,instrument,price\nT-1,ES,10\n")
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("MISSING_HEADERS"))
                .andExpect(jsonPath("$.message").value(containsString("trade_timestamp")))
                .andExpect(jsonPath("$.message").value(containsString("trader_id")));
        assertThat(countRows("trade_import_batches")).isZero();
    }

    @Test
    void missingFilePartIsABadRequestWithTheStandardErrorBody() throws Exception {
        mvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart("/api/imports"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("BAD_REQUEST"))
                .andExpect(jsonPath("$.path").value("/api/imports"))
                .andExpect(jsonPath("$.stackTrace").doesNotExist());
    }

    @Test
    void malformedQuotingFailsTheBatchAndRollsBackEveryRow() throws Exception {
        uploadCsv("G-1,ES,2025-03-10T14:30:00Z,BUY,5100,10,USD,A\n"
                + "G-2,ES,2025-03-10T14:30:00Z,BUY,5100,10,USD,\"never closed\nG-3,")
                .andExpect(status().isUnprocessableEntity())
                .andExpect(jsonPath("$.code").value("CSV_PARSE_ERROR"));

        assertThat(countRows("trades")).isZero(); // transaction rolled back, no partial data
        assertThat(jdbc.queryForObject("SELECT status FROM trade_import_batches", String.class)).isEqualTo("FAILED");
        mvc.perform(get("/api/imports")).andExpect(jsonPath("$.content[0].status").value("FAILED"))
                .andExpect(jsonPath("$.content[0].failureReason").value(containsString("malformed")));
    }

    @Test
    void enforcesTheConfiguredMaximumUploadSize() throws Exception {
        jdbc.update("UPDATE validation_rules SET rule_value = '1' WHERE rule_key = 'MAX_UPLOAD_SIZE_MB'");
        StringBuilder big = new StringBuilder(HEADER).append('\n');
        String line = "X-%d,ES,2025-03-10T14:30:00Z,BUY,5100.25,10,USD,TRD-LONG-NAME-PADDING-PADDING\n";
        for (int i = 0; i < 20_000; i++) {
            big.append(line.formatted(i));
        }
        assertThat(big.length()).isGreaterThan(1024 * 1024);
        upload("big.csv", "text/csv", big.toString())
                .andExpect(status().isPayloadTooLarge())
                .andExpect(jsonPath("$.code").value("FILE_TOO_LARGE"));
        assertThat(countRows("trades")).isZero();
    }

    @Test
    void importsManyRowsInChunks() throws Exception {
        StringBuilder csv = new StringBuilder();
        for (int i = 1; i <= 1_300; i++) {
            csv.append("B-").append(i).append(",ES,2025-03-10T14:30:00Z,BUY,5100.25,1,USD,A\n");
        }
        csv.append("B-1,ES,2025-03-10T14:30:00Z,BUY,5100.25,1,USD,A\n"); // duplicate across chunk boundary
        uploadCsv(csv.toString())
                .andExpect(jsonPath("$.batch.totalRows").value(1_301))
                .andExpect(jsonPath("$.batch.validRows").value(1_300))
                .andExpect(jsonPath("$.batch.invalidRows").value(1));
        List<Integer> rows = jdbc.queryForList("SELECT row_number FROM trade_validation_errors", Integer.class);
        assertThat(rows).containsExactly(1_302);
    }

    @Test
    void requestsForwardedByTheUiProxyWithAnOriginHeaderAreAccepted() throws Exception {
        // Regression: the Next.js proxy forwards the browser Origin; the API must not reject it (it once returned 403).
        mvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders
                        .multipart("/api/imports")
                        .file(new org.springframework.mock.web.MockMultipartFile("file", "o.csv", "text/csv",
                                (HEADER + "\nO-1,ES,2025-03-10T14:30:00Z,BUY,1,1,USD,A\n").getBytes()))
                        .header("Origin", "http://localhost:3100"))
                .andExpect(status().isCreated());
        mvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get("/api/rules")
                        .header("Origin", "http://localhost:3100"))
                .andExpect(status().isOk());
    }

    @Test
    void healthEndpointReportsUp() throws Exception {
        mvc.perform(get("/actuator/health")).andExpect(status().isOk()).andExpect(jsonPath("$.status").value("UP"));
    }
}
